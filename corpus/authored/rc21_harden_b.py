"""RC2.1 hardening — mixed multi-vulnerability examples (+ a few singles).

Teaches the model to emit MULTIPLE findings for code with several distinct issues
(the benchmark mix-* cases were frequently missed). Distinct from the benchmark
mix cases and prior batches; no benchmark answers copied. Provenance
hand_authored; honest review_quality.
"""
from corpus.builder import finding, vuln


def V(source_backed: bool = False, **kw):
    e = vuln(**kw)
    e["review_quality"] = {
        "source_backed": source_backed,
        "patch_reviewed": True,
        "safety_layer_consistent": True,
        "category_confirmed": True,
    }
    return e


def _f(category, file, line, description, exploit, fix, patch, severity=None):
    return finding(category, file, line, description, exploit, fix, patch, severity=severity)


