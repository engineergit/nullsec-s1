def C(*, id, lang, framework, file, code, summary):
    e = secure(id=id, lang=lang, framework=framework, file=file, code=code, summary=summary)
    e["review_quality"] = {
        "source_backed": False,
        "patch_reviewed": True,
        "safety_layer_consistent": True,
        "category_confirmed": True,
    }
    return e


def V(
    *,
    id,
    lang,
    framework,
    file,
    code,
    category,
    line,
    description,
    exploit,
    fix,
    patch,
    severity=None,
    fail_dims=(),
    extra_findings=None,
):
    e = vuln(
        id=id,
        lang=lang,
        framework=framework,
        file=file,
        code=code,
        category=category,
        line=line,
        description=description,
        exploit=exploit,
        fix=fix,
        patch=patch,
        severity=severity,
        fail_dims=fail_dims,
        extra_findings=extra_findings,
    )
    e["review_quality"] = {
        "source_backed": False,
        "patch_reviewed": True,
        "safety_layer_consistent": True,
        "category_confirmed": True,
    }
    return e


def F(category, file, line, description, exploit, fix, patch, severity=None):
    return finding(category, file, line, description, exploit, fix, patch, severity=severity)


