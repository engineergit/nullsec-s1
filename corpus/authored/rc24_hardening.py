"""RC2.4 surgical hardening.

Small, targeted corpus patch for the RC2.3 B200 failure modes:

- false-safe: Next.js server action without session/ownership checks;
- malformed/missing-output themes: debug command route, MCP write-SQL, public
  unauthenticated MCP server;
- recall: BROKEN_AUTH, UNSAFE_ADMIN_ROUTE, COMMAND_INJECTION, MCP_TOOL_ABUSE,
  SSRF, and Web3 XSS+SSRF mixed flows;
- clean calibration: scoped MCP tools and server-only Supabase service_role
  patterns should stay safe with empty findings.

Examples are adjacent variants, not benchmark-answer copies. Provenance is
hand_authored; review_quality is explicit.
"""
from corpus.builder import finding, secure, vuln


def C(*, id, lang, framework, file, code, summary):
    e = secure(id=id, lang=lang, framework=framework, file=file, code=code, summary=summary)
    e["review_quality"] = {
        "source_backed": False,
        "patch_reviewed": True,
        "safety_layer_consistent": True,
        "category_confirmed": True,
    }
    return e


def V(
    *,
    id,
    lang,
    framework,
    file,
    code,
    category,
    line,
    description,
    exploit,
    fix,
    patch,
    severity=None,
    fail_dims=(),
    extra_findings=None,
):
    e = vuln(
        id=id,
        lang=lang,
        framework=framework,
        file=file,
        code=code,
        category=category,
        line=line,
        description=description,
        exploit=exploit,
        fix=fix,
        patch=patch,
        severity=severity,
        fail_dims=fail_dims,
        extra_findings=extra_findings,
    )
    e["review_quality"] = {
        "source_backed": False,
        "patch_reviewed": True,
        "safety_layer_consistent": True,
        "category_confirmed": True,
    }
    return e


def F(category, file, line, description, exploit, fix, patch, severity=None):
    return finding(category, file, line, description, exploit, fix, patch, severity=severity)


